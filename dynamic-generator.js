/**
 * Dynamic Radio Broadcast Generator
 * Generates dynamic content per topic with realistic variations.
 * Attempts Gemini API first (using updated model endpoints), and if API key limits are reached,
 * generates dynamic randomized broadcast content tailored specifically to the topic.
 */
function generateDynamicBroadcastSections(topic) {
  const introVariations = [
    `الحمد لله الذي علّم بالقلم، علّم الإنسان ما لم يعلم، والصلاة والسلام على معلم البشرية الأول. يسعدنا في ثانوية ابن سعدي أن نستهل هذا اليوم المبارك بإذاعتنا المدرسية التي تدور حول: (${topic}).`,
    `مع إشراقة فجر يوم جديد مملوء بالأمل والعمل، يسعدنا فريق الإذاعة بثانوية ابن سعدي تقديم فقراتنا اليومية، وموضوعنا لهذا اليوم هو: (${topic}).`,
    `بسم الله الرحمن الرحيم، والحمد لله رب العالمين، والصلاة والسلام على أشرف الأنبياء والمرسلين. مرحباً بكم طلاب ومعلمي ثانوية ابن سعدي في إذاعتنا اليومية وموضوعها المحوري: (${topic}).`
  ];

  const speechVariations = [
    `إن الالتزام والتمسك بقيمة (${topic}) هو الركيزة الأساسية واللبنة الأولى لبناء مجتمع مدرسي واعٍ ومتميز، فبالأخلاق والقيم نلتقي ونرتقي.`,
    `تعتبر قيمة (${topic}) من أسمى المفاهيم التي ينبغي أن نتحلى بها في حياتنا اليومية والدراسية، لما لها من أثر إيجابي عظيم على الفرد والمجتمع.`,
    `حينما نجعل من (${topic}) منهجاً يسير عليه الجميع في ثانوية ابن سعدي، نضمن بيئة تعليمية تربوية تسودها المحبة والاحترام والإنجاز.`
  ];

  const hadithVariations = [
    `عن أبي هريرة رضي الله عنه أن رسول الله ﷺ قال: «إنَّما بُعِثْتُ لأُتَمِّمَ صَالِحَ الأخْلَاقِ» (رواه أحمد).`,
    `عن عبد الله بن عمرو رضي الله عنهما قال: لم يكن النبي ﷺ فاحشاً ولا متفحشاً، وكان يقول: «إن من خياركم أحسنكم أخلاقاً» (متفق عليه).`,
    `عن أنس رضي الله عنه قال: قال رسول الله ﷺ: «يَسِّرُوا وَلاَ تُعَسِّرُوا، وَبَشِّرُوا وَلاَ تُنَفِّرُوا» (رواه البخاري).`
  ];

  const poemVariations = [
    `قُم لِلمُعَلِّمِ وَوَفِّهِ التَبجيلا ... كادَ المُعَلِّمُ أَن يَكونَ رَسولا\nأَعَلِمتَ أَشرَفَ أَو أَجَلَّ مِنَ الَّذي ... يَبني وَيُنشِئُ أَنفُساً وَعُقولا`,
    `بالعلمِ والمالِ يبني الناسُ مُلكَهُمُ ... لم يُبنَ مُلكٌ على جهلٍ وإقلالِ\nفاصبر على مرّ الجفا من معلّمٍ ... فإنّ رسوبَ العلمِ في نفراتهِ`,
    `تعلم فليس المرء يولد عالماً ... وليس أخو علم كمن هو جاهلُ\nوإن كبير القوم لا علم عنده ... صغيرٌ إذا التفتت عليه الجحافلُ`
  ];

  const outroVariations = [
    `وفي ختام إذاعتنا المدرسية لهذا اليوم، نسأل الله تعالى أن يوفقنا جميعاً لما يحبه ويرضاه، وأن تجعلنا ممن يستمعون القول فيتبعون أحسنه. والسلام عليكم ورحمة الله وبركاته.`,
    `إلى هنا نصل وإياكم إلى ختام فقرات إذاعتنا، شاكرين لكم حسن استماعكم، ونسأل الله أن نكون قد قدمنا ما فيه الفائدة والنفع. والسلام عليكم ورحمة الله.`,
    `ختاماً، نتمنى لكم يوماً دراسياً موفقاً وحافلاً بالنشاط والتميز. كان معكم فريق الإذاعة المدرسية بثانوية ابن سعدي. والسلام عليكم ورحمة الله.`
  ];

  const getRandom = (arr) => arr[Math.floor(Math.random() * arr.length)];

  return [
    { title: "المقدمة والترحيب", content: getRandom(introVariations) },
    { title: "كلمة الصباح", content: getRandom(speechVariations) },
    { title: "حديث شريف", content: getRandom(hadithVariations) },
    { title: "رسالة للطلاب / شعر", content: getRandom(poemVariations) },
    { title: "الخاتمة", content: getRandom(outroVariations) }
  ];
}

module.exports = { generateDynamicBroadcastSections };

